"""Douyin public search adapter.

The web endpoint is intentionally conservative: it uses the public search page
or documented-in-browser JSON response, and never attempts to calculate anti-bot
signatures or bypass a verification page.
"""

from __future__ import annotations

import html
import json
import re
from typing import Any, Iterator
from urllib.parse import quote, unquote

from exceptions import ChallengeDetected, CollectorError
from media_tools import ocr_image_url, whisper_transcribe_url
from models import Comment, ContentItem, DeepContent, Engagement
from utils import clean_html, iso_from_timestamp, safe_int

from .base import BaseCollector, ProgressCallback


class DouyinCollector(BaseCollector):
    name = "douyin"
    api_url = "https://www.douyin.com/aweme/v1/web/general/search/single/"

    def _credential_headers(self) -> dict[str, str]:
        headers = {
            "Referer": "https://www.douyin.com/",
            "Accept": "application/json, text/plain, */*",
        }
        if self.settings.douyin_cookie:
            headers["Cookie"] = self.settings.douyin_cookie
        return headers

    @staticmethod
    def _hashtags(row: dict[str, Any]) -> list[str]:
        values: list[str] = []
        for extra in row.get("text_extra") or row.get("textExtra") or []:
            if isinstance(extra, dict) and extra.get("hashtag_name"):
                values.append(str(extra["hashtag_name"]))
        return list(dict.fromkeys(values))

    def _convert(self, row: dict[str, Any], keyword: str, query: str) -> ContentItem | None:
        row = row.get("aweme_info") or row.get("aweme") or row
        item_id = str(row.get("aweme_id") or row.get("awemeId") or row.get("id") or "")
        if not item_id:
            return None
        author = row.get("author") or {}
        stats = row.get("statistics") or row.get("stats") or {}
        desc = clean_html(str(row.get("desc") or row.get("description") or ""))
        hashtags = self._hashtags(row)
        video = row.get("video") or {}
        cover = (video.get("cover") or video.get("origin_cover") or {}).get("url_list") or []
        cover_url = str(cover[0]) if cover else ""
        return ContentItem(
            id=item_id,
            platform=self.name,
            keyword=keyword,
            content_type="video",
            title=desc[:120],
            summary=desc[:1000],
            author=str(author.get("nickname") or author.get("unique_id") or ""),
            published_at=iso_from_timestamp(row.get("create_time")),
            engagement=Engagement(
                likes=safe_int(stats.get("digg_count") or stats.get("like_count")),
                comments=safe_int(stats.get("comment_count")),
                shares=safe_int(stats.get("share_count")),
                views=safe_int(stats.get("play_count")),
            ),
            url=str(row.get("share_url") or f"https://www.douyin.com/video/{item_id}"),
            extra={
                "hashtags": hashtags,
                "cover_url": cover_url,
                "music_title": str((row.get("music") or {}).get("title", "")),
                "author_followers": safe_int(author.get("follower_count")),
                "search_query": query,
                "douyin_raw": {"aweme_id": item_id},
            },
        )

    def _api_rows(self, query: str, keyword: str) -> list[ContentItem]:
        items: list[ContentItem] = []
        cursor = 0
        for _ in range(self.config.pages):
            try:
                payload = self.get_json(
                    self.api_url,
                    params={
                        "device_platform": "webapp",
                        "aid": 6383,
                        "channel": "channel_pc_web",
                        "search_channel": "aweme_general",
                        "keyword": query,
                        "search_source": "normal_search",
                        "query_correct_type": 1,
                        "is_filter_search": 0,
                        "count": self.config.page_size,
                        "cursor": cursor,
                    },
                )
            except ChallengeDetected:
                raise
            except Exception as exc:
                if items:
                    self.note_partial("search", exc)
                    break
                raise
            # Douyin answers 200 with an empty data array and names the reason in
            # search_nil_info. "verify_check" means it wants a request signature
            # (a_bogus / X-Bogus) that is generated by their obfuscated JS; a
            # valid login Cookie is not enough. This project does not forge that
            # signature, so report the real cause instead of "0 条".
            nil_info = payload.get("search_nil_info") or {}
            if nil_info.get("search_nil_type") == "verify_check" and not payload.get("data"):
                raise ChallengeDetected(
                    "抖音要求请求签名校验（接口返回 search_nil_type=verify_check）；"
                    "Cookie 本身有效，但抖音仍判定为自动化请求并要求 a_bogus/X-Bogus 签名。"
                    "本项目不伪造该签名，因此抖音搜索无法通过此检查——"
                    "建议改用免凭据的 douyin_hot（抖音热搜榜）平台，或手动导出所需内容。"
                )
            rows = payload.get("data") or []
            if isinstance(rows, dict):
                rows = rows.get("data") or rows.get("aweme_list") or []
            converted = [self._convert(row, keyword, query) for row in rows if isinstance(row, dict)]
            items.extend(item for item in converted if item)
            if not rows or not payload.get("has_more"):
                break
            cursor = safe_int(payload.get("cursor")) or cursor + self.config.page_size
        return items

    @staticmethod
    def _walk_json(value: Any) -> Iterator[dict[str, Any]]:
        if isinstance(value, dict):
            if value.get("aweme_id") or value.get("awemeId"):
                yield value
            for child in value.values():
                yield from DouyinCollector._walk_json(child)
        elif isinstance(value, list):
            for child in value:
                yield from DouyinCollector._walk_json(child)

    def _page_rows(self, query: str, keyword: str) -> list[ContentItem]:
        page_url = f"https://www.douyin.com/search/{quote(query, safe='')}"
        response = self.request("GET", page_url)
        found: dict[str, ContentItem] = {}
        scripts = re.findall(r'<script[^>]*id="([^"]+)"[^>]*>(.*?)</script>', response.text, re.S | re.I)
        for script_id, content in scripts:
            if script_id not in {"RENDER_DATA", "SIGI_STATE", "__NEXT_DATA__"}:
                continue
            try:
                parsed = json.loads(html.unescape(unquote(content)))
            except (TypeError, ValueError):
                continue
            for row in self._walk_json(parsed):
                item = self._convert(row, keyword, query)
                if item:
                    found[item.id] = item
        return list(found.values())

    def _page_rows_safe(self, query: str, keyword: str) -> list[ContentItem]:
        """Search-page fallback; it is an SPA shell so it usually yields nothing."""
        try:
            return self._page_rows(query, keyword)
        except ChallengeDetected:
            self.log.info("抖音搜索页返回验证码中间页（预期行为）")
        except Exception as exc:
            self.log.warning("抖音搜索页解析失败: %s", exc)
        return []

    def search(self, keyword: str, progress: ProgressCallback | None = None) -> list[ContentItem]:
        items: list[ContentItem] = []
        api_failed = False
        try:
            items = self._api_rows(keyword, keyword)
        except ChallengeDetected:
            # Signature / captcha wall: no fallback can get past it, and retrying
            # the search page only doubles the chance of another challenge.
            raise
        except Exception as api_error:
            api_failed = True
            self.log.warning("抖音 JSON 搜索不可用，尝试公开搜索页: %s", api_error)
        if not items:
            items = self._page_rows_safe(keyword, keyword)
        if not items:
            hint = (
                "抖音未返回任何可用内容（接口 200 但 data 为空，搜索页为 SPA 外壳）"
            )
            if not self.settings.douyin_cookie:
                hint += "；当前未配置 DOUYIN_COOKIE"
            else:
                hint += "；已配置 DOUYIN_COOKIE，说明不是登录态问题"
            if api_failed:
                hint += "；JSON 接口也报错了，请查看上一条日志"
            hint += "。这不是「没有结果」，而是请求未被抖音接受"
            self.note_partial("search", hint)
        if progress:
            progress(self.name, 1, 1, f"{keyword}: {len(items)} 条")
        return list({item.id: item for item in items}.values())

    def _comments(self, item: ContentItem, limit: int = 100) -> list[Comment]:
        payload = self.get_json(
            "https://www.douyin.com/aweme/v1/web/comment/list/",
            params={"aweme_id": item.id, "cursor": 0, "count": min(limit, 50), "item_type": 0},
        )
        rows = payload.get("comments") or payload.get("data") or []
        comments: list[Comment] = []
        for row in rows:
            user = row.get("user") or {}
            comments.append(
                Comment(
                    text=clean_html(str(row.get("text", ""))),
                    likes=safe_int(row.get("digg_count") or row.get("like_count")),
                    author=str(user.get("nickname") or ""),
                    published_at=iso_from_timestamp(row.get("create_time")),
                )
            )
        comments.sort(key=lambda value: value.likes, reverse=True)
        return comments[:limit]

    def deep_dive(self, item: ContentItem) -> DeepContent:
        errors: list[str] = []
        try:
            comments = self._comments(item)
        except Exception as exc:
            errors.append(f"comments: {exc}")
            comments = []
        full_content = whisper_transcribe_url(item.url, self.settings) or item.summary
        media_text = ocr_image_url(self.client, str(item.extra.get("cover_url", "")), self.settings)
        return DeepContent(base=item, full_content=full_content, comments=comments, media_text=media_text, errors=errors)
