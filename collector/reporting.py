def _png_chunk(kind: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)


def _simple_bar_png(path: Path, series: list[list[float]], width: int = 900, height: int = 500) -> None:
    """Dependency-free visual fallback: grouped 12-bin histograms."""
    pixels = bytearray([255] * (width * height * 3))

    def rect(x0: int, y0: int, x1: int, y1: int, color: tuple[int, int, int]) -> None:
        for y in range(max(0, y0), min(height, y1)):
            for x in range(max(0, x0), min(width, x1)):
                offset = (y * width + x) * 3
                pixels[offset : offset + 3] = bytes(color)

    rect(55, 35, 58, height - 45, (45, 55, 72))
    rect(55, height - 48, width - 25, height - 45, (45, 55, 72))
    all_values = [value for values in series for value in values]
    if all_values:
        maximum = max(all_values) or 1.0
        bins = 12
        histograms: list[list[int]] = []
        for values in series:
            counts = [0] * bins
            for value in values:
                counts[min(int(value / maximum * bins), bins - 1)] += 1
            histograms.append(counts)
        max_count = max((count for hist in histograms for count in hist), default=1)
        colors = [(64, 116, 217), (230, 126, 34), (47, 158, 68), (151, 92, 183)]
        plot_w, plot_h = width - 90, height - 90
        group_w = plot_w / bins
        bar_w = max(2, int(group_w / max(len(series), 1)) - 2)
        for bin_index in range(bins):
            for series_index, hist in enumerate(histograms):
                bar_h = int(hist[bin_index] / max_count * (plot_h - 10))
                x = int(60 + bin_index * group_w + series_index * (bar_w + 2))
                rect(x, height - 48 - bar_h, x + bar_w, height - 48, colors[series_index % len(colors)])
    raw = b"".join(b"\x00" + bytes(pixels[y * width * 3 : (y + 1) * width * 3]) for y in range(height))
    png = b"\x89PNG\r\n\x1a\n"
    png += _png_chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
    png += _png_chunk(b"IDAT", zlib.compress(raw, 9)) + _png_chunk(b"IEND", b"")
    path.write_bytes(png)


def write_engagement_distribution(path: Path, items: Iterable[ContentItem]) -> None:
    rows = list(items)
    try:
        mpl_cache = Path(tempfile.gettempdir()) / "social-media-mpl-cache"
        mpl_cache.mkdir(parents=True, exist_ok=True)
        os.environ.setdefault("MPLCONFIGDIR", str(mpl_cache))
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        fig, ax = plt.subplots(figsize=(9, 5))
        for platform in sorted({item.platform for item in rows}):
            values = [item.engagement_score for item in rows if item.platform == platform]
            if values:
                ax.hist(values, bins=min(20, max(5, len(values))), alpha=0.5, label=platform)
        ax.set_title("Engagement Score Distribution")
        ax.set_xlabel("score")
        ax.set_ylabel("items")
        if rows:
            ax.legend()
        fig.tight_layout()
        fig.savefig(path, dpi=160)
        plt.close(fig)
    except Exception:
        grouped = [
            [item.engagement_score for item in rows if item.platform == platform]
            for platform in sorted({item.platform for item in rows})
        ]
        _simple_bar_png(path, grouped)


def write_wordcloud(path: Path, top_keywords: list[dict]) -> None:
    frequencies = {str(row["keyword"]): int(row["count"]) for row in top_keywords if row.get("keyword")}
    try:
        from wordcloud import WordCloud

        candidates = [
            Path("C:/Windows/Fonts/msyh.ttc"),
            Path("/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"),
        ]
        font = next((str(candidate) for candidate in candidates if candidate.exists()), None)
        cloud = WordCloud(width=1200, height=700, background_color="white", font_path=font, collocations=False)
        cloud.generate_from_frequencies(frequencies or {"empty": 1}).to_file(str(path))
    except Exception:
        # The fallback visual uses term counts as a compact ranked distribution.
        _simple_bar_png(path, [[float(value) for value in frequencies.values()]])


def write_dataset_readme(storage: DatasetStorage, metadata: dict) -> None:
    platforms = ", ".join(metadata.get("platforms", []))
    text = f"""# Social Media Public-Content Dataset

This directory was generated by the social-media research collector.

- Keywords: {", ".join(metadata.get("keywords", []))}
- Platforms: {platforms}
- Mode: {metadata.get("mode", "quick")}
- Mock data: {metadata.get("mock", False)}
- Total L1 records: {metadata.get("total_items", 0)}
- Total L2 records: {metadata.get("deep_items", 0)}

## Layout

- `raw/*.jsonl` and `raw/*.db`: normalized L1 records.
- `deep/*_deep.jsonl` and `deep/*_deep.db`: selected L2 records.
- `report/overview.json`: run totals, warnings and screening summary.
- `report/top_keywords.json`: up to 100 frequent terms.
- `report/engagement_dist.png`: engagement score histogram.
- `report/wordcloud.png`: frequent-term word cloud (ranked bar fallback on minimal installs).
- `config_snapshot.json`: redacted settings used by this run.

SQLite files contain an `items` table. The complete record is stored as JSON in
the `payload` column, with indexed identity and selection fields alongside it.

## Compliance

Only collect content that is publicly visible and permitted by the platform's
terms/API policy. Respect robots.txt, rate limits, copyright, privacy, deletion
requests and applicable law. Do not republish personal data. Credentials and
cookies are deliberately omitted from this dataset.
"""
    (storage.root / "README.md").write_text(text, encoding="utf-8")


def write_reports(storage: DatasetStorage, items: list[ContentItem], analysis: dict, run: dict) -> None:
    overview = {**run, "analysis": {key: value for key, value in analysis.items() if key != "top_keywords"}}
    storage.write_json("report/overview.json", overview)
    storage.write_json("report/top_keywords.json", analysis.get("top_keywords", []))
    write_engagement_distribution(storage.report_dir / "engagement_dist.png", items)
    write_wordcloud(storage.report_dir / "wordcloud.png", analysis.get("top_keywords", []))
    write_dataset_readme(storage, run)
